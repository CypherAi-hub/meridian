test("one provider failing does not drop the tape", () => {
  const next = applyTape(createDesk(), tape());
  assert.ok(next.tokens.length >= 1);
  assert.ok(next.sources.some((s) => s.status === "offline"));
  assert.equal(next.realData, true);
});

test("raw observations exist on the tape even with no strategy take", () => {
  const next = applyTape(createDesk(), tape());
  assert.equal(next.positions.length, 0);
  assert.ok(next.tokens.length >= 1);
  assert.ok(next.tokens[0].priceUsd.value);
});

