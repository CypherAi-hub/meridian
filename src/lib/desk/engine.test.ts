function tape(partial: Partial<TokenLive> = {}): MarketTape {
  const now = Date.now();
  const base = blankSnapshot("Mint111111111111111111111111111111111111111", now, now);
  const token: TokenLive = {
    ...base,
    symbol: "TEST",
    name: "Test",
    createdAt: now - 10 * 60_000,
    history: [1, 1.01],
    prevLiq: 80_000,
    prevVolume5m: 12_000,
    prevBuyers: 40,
    rugged: false,
    priceUsd: field(1.02, now, now, "dexscreener"),
    liquidityUsd: field(80_000, now, now, "dexscreener"),
    mcapUsd: field(400_000, now, now, "dexscreener"),
    volume5mUsd: field(12_000, now, now, "dexscreener"),
    ...partial,
  };
  return {
    ingestedAt: now,
    eventTime: now,
    fetchMs: 40,
    solPriceUsd: 180,
    tokens: [token],
    sources: [
      { id: "dexscreener", status: "live", lagMs: 40, lastOkAt: now, detail: "ok" },
      { id: "jupiter", status: "offline", lagMs: null, lastOkAt: null, detail: "down" },
    ],
  };
}

